"""Export an ATT&CK Navigator layer (layer format 4.5) so the result opens as a heatmap."""
from __future__ import annotations

from .attack import AttackData
from .coverage import COVERED, NO_GUIDANCE, OBSERVABLE, TELEMETRY, CoverageReport

COLORS = {COVERED: "#66b032", OBSERVABLE: "#fb9a29", TELEMETRY: "#c9c9c9"}


def to_layer(report: CoverageReport, attack: AttackData, name: str = "SOC detection coverage") -> dict:
    techniques = []
    for tid, res in report.results.items():
        if res.status == NO_GUIDANCE:
            continue
        comment = {
            COVERED: "Wazuh rules: " + ", ".join(res.rule_ids),
            OBSERVABLE: "No rule yet. Observable via: " + ", ".join(res.matching_log_sources),
            TELEMETRY: "No rule; needs new telemetry: " + ", ".join(res.needed_log_sources[:6]),
        }[res.status]
        for tactic in res.tactics:
            techniques.append({"techniqueID": tid, "tactic": tactic, "color": COLORS[res.status],
                               "comment": comment, "enabled": True})
    return {
        "name": name,
        "versions": {"attack": attack.version.split(".")[0], "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": "Generated by soc-coverage-analyzer. Green = rule mapped, orange = candidate gap, grey = telemetry gap.",
        "techniques": techniques,
        "legendItems": [
            {"label": "Covered by a Wazuh rule (static mapping)", "color": COLORS[COVERED]},
            {"label": "Candidate gap: observable with collected logs", "color": COLORS[OBSERVABLE]},
            {"label": "Telemetry gap: needs new log sources", "color": COLORS[TELEMETRY]},
        ],
    }
